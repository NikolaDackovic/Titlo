import { formatAssTime, parseTimecode } from '../domain/time'
import type { ExportCue, ParsedCue, ParsedSubtitles, ParseWarning, SerializeOptions } from './types'
import { SubtitleParseError } from './types'
import { t as L } from '../i18n'

/**
 * Advanced SubStation Alpha (.ass / .ssa) support.
 *
 * Everything before the dialogue lines ([Script Info], [V4+ Styles], the [Events]
 * Format line) is preserved verbatim as the header so styles survive a round trip.
 * Per-line fields (Layer, Style, Name, Margins, Effect) are preserved in meta.
 * `\N` hard breaks become `\n` for editing and are converted back on export.
 */

const DEFAULT_FORMAT = ['Layer', 'Start', 'End', 'Style', 'Name', 'MarginL', 'MarginR', 'MarginV', 'Effect', 'Text']

export const DEFAULT_ASS_HEADER = [
  '[Script Info]',
  '; Script generated by Titlo',
  'ScriptType: v4.00+',
  'WrapStyle: 0',
  'ScaledBorderAndShadow: yes',
  'PlayResX: 1920',
  'PlayResY: 1080',
  '',
  '[V4+ Styles]',
  'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
  'Style: Default,Arial,64,&H00FFFFFF,&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,3,1,2,80,80,60,1',
  '',
  '[Events]',
  `Format: ${DEFAULT_FORMAT.join(', ')}`,
].join('\n')

const splitFields = (value: string, count: number) => {
  const fields: string[] = []
  let rest = value
  for (let k = 0; k < count - 1; k += 1) {
    const comma = rest.indexOf(',')
    if (comma === -1) return null
    fields.push(rest.slice(0, comma).trim())
    rest = rest.slice(comma + 1)
  }
  fields.push(rest) // Text keeps its commas and leading spaces.
  return fields
}

export function parseAss(input: string): ParsedSubtitles {
  const text = input.replace(/^﻿/, '').replace(/\r\n?/g, '\n')
  const lines = text.split('\n')
  const warnings: ParseWarning[] = []
  const cues: ParsedCue[] = []
  const headerLines: string[] = []

  let section = ''
  let format: string[] | null = null
  let comments = 0
  let drawings = 0
  const ignoredSections = new Set<string>()

  lines.forEach((line, index) => {
    const trimmed = line.trim()
    const sectionMatch = trimmed.match(/^\[(.+)\]$/)
    if (sectionMatch) {
      section = sectionMatch[1].toLowerCase()
      if (section === 'fonts' || section === 'graphics') {
        ignoredSections.add(sectionMatch[1])
        return
      }
      headerLines.push(trimmed)
      return
    }
    if (section === 'fonts' || section === 'graphics') return

    if (section !== 'events') {
      headerLines.push(line)
      return
    }

    if (/^Format\s*:/i.test(trimmed)) {
      format = trimmed
        .replace(/^Format\s*:/i, '')
        .split(',')
        .map((f) => f.trim())
      headerLines.push(trimmed)
      return
    }
    if (/^Comment\s*:/i.test(trimmed)) {
      comments += 1
      return
    }
    if (!/^Dialogue\s*:/i.test(trimmed)) {
      if (trimmed) warnings.push({ kind: 'skipped', line: index + 1, message: L('Unrecognised event line skipped: "{slice}"', { slice: trimmed.slice(0, 60) }) })
      return
    }

    const fieldsNames = format ?? DEFAULT_FORMAT
    const fields = splitFields(line.replace(/^\s*Dialogue\s*:\s?/i, ''), fieldsNames.length)
    if (!fields) {
      warnings.push({ kind: 'skipped', line: index + 1, message: L('Dialogue line has too few fields; skipped.') })
      return
    }
    const record: Record<string, string> = {}
    fieldsNames.forEach((name, k) => (record[name] = fields[k]))

    const start = parseTimecode(record.Start ?? '')
    const end = parseTimecode(record.End ?? '')
    if (start === null || end === null) {
      warnings.push({ kind: 'skipped', line: index + 1, message: L('Invalid ASS timing "{Start} / {End}"; line skipped.', { Start: record.Start, End: record.End }) })
      return
    }

    const rawText = record.Text ?? ''
    if (/\{[^}]*\\p[1-9]/.test(rawText)) drawings += 1

    const meta: Record<string, string> = {}
    for (const [name, value] of Object.entries(record)) {
      if (name !== 'Start' && name !== 'End' && name !== 'Text') meta[`ass${name}`] = value
    }

    cues.push({ start, end, text: rawText.replace(/\\N/g, '\n'), meta })
  })

  if (!format) warnings.push({ kind: 'repaired', message: L('No [Events] Format line found; the standard v4+ field order was assumed.') })
  if (comments) warnings.push({ kind: 'unsupported', message: L('{comments} "Comment" event(s) are not imported and will not be exported.', { comments }) })
  if (drawings) warnings.push({ kind: 'unsupported', message: L('{drawings} line(s) contain vector drawing commands (\\p); they are kept as raw text but cannot be translated meaningfully.', { drawings }) })
  for (const name of ignoredSections) {
    warnings.push({ kind: 'unsupported', message: L('[{name}] section (embedded attachments) is not preserved.', { name }) })
  }
  if (cues.length === 0) throw new SubtitleParseError('No Dialogue lines were found in the ASS/SSA file.')

  // Ensure the header ends with the [Events] section + Format line.
  let header = headerLines.join('\n').replace(/\n{3,}/g, '\n\n').trim()
  if (!/\[Events\]/i.test(header)) header += `\n\n[Events]\nFormat: ${DEFAULT_FORMAT.join(', ')}`

  return { format: 'ass', cues, header, warnings }
}

const formatFromHeader = (header: string) => {
  const eventsIdx = header.search(/\[Events\]/i)
  const tail = eventsIdx >= 0 ? header.slice(eventsIdx) : ''
  const m = tail.match(/^Format\s*:(.*)$/im)
  return m ? m[1].split(',').map((f) => f.trim()) : DEFAULT_FORMAT
}

export function serializeAss(cues: ExportCue[], header: string | null, options: SerializeOptions): string {
  const nl = options.lineEnding === 'crlf' ? '\r\n' : '\n'
  let head = header ?? DEFAULT_ASS_HEADER
  if (!/\[Events\]/i.test(head)) head += `\n\n[Events]\nFormat: ${DEFAULT_FORMAT.join(', ')}`
  // Sections that follow [Events] in the original file (e.g. Aegisub's [Aegisub Extradata])
  // must come AFTER the dialogue lines, otherwise players read the dialogue as extradata.
  let trailer = ''
  const eventsAt = head.search(/^\[Events\]\s*$/im)
  const after = head.slice(eventsAt + 1)
  const nextSection = after.search(/^\[[^\]]+\]\s*$/m)
  if (nextSection >= 0) {
    trailer = after.slice(nextSection).trim()
    head = head.slice(0, eventsAt + 1 + nextSection).trimEnd()
  }
  const format = formatFromHeader(head)

  const defaults: Record<string, string> = {
    Layer: '0',
    Style: 'Default',
    Name: '',
    MarginL: '0',
    MarginR: '0',
    MarginV: '0',
    Effect: '',
    Marked: 'Marked=0',
  }

  const dialogue = cues.map((cue) => {
    const values = format.map((name) => {
      if (name === 'Start') return formatAssTime(cue.start)
      if (name === 'End') return formatAssTime(cue.end)
      if (name === 'Text') return cue.text.replace(/\r?\n/g, '\\N')
      return cue.meta?.[`ass${name}`] ?? defaults[name] ?? ''
    })
    return `Dialogue: ${values.join(',')}`
  })

  const body = [head.replace(/\r?\n/g, nl), ...dialogue].join(nl) + nl
  return trailer ? body + nl + trailer.replace(/\r?\n/g, nl) + nl : body
}
